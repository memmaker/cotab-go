// Command tablegen writes engine/tables.go: the data tables of the DOS
// START.EXE that the engine reads, as named Go values. It runs only at
// `go generate` time (engine/tables_spec.go), so the game itself never reads
// the executable.
//
//	tablegen START.EXE > tables.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"cotab/exe"
	"cotab/tablespec"
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: tablegen START.EXE")
	}
	img, err := exe.LoadCurse(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/tablegen from START.EXE; DO NOT EDIT.\n\npackage engine\n\n")
	for _, t := range tablespec.Tables {
		if t.Doc != "" {
			for _, l := range strings.Split(t.Doc, "\n") {
				fmt.Fprintf(&b, "// %s\n", l)
			}
		}
		raw := img.Bytes(t.At, t.Len*t.Kind.Size())
		switch t.Kind {
		case tablespec.Bytes:
			fmt.Fprintf(&b, "var %s = [%d]byte{%s}\n\n", t.Name, t.Len, list(raw, 1, false))
		case tablespec.Signed:
			fmt.Fprintf(&b, "var %s = [%d]int8{%s}\n\n", t.Name, t.Len, list(raw, 1, true))
		case tablespec.Words:
			fmt.Fprintf(&b, "var %s = [%d]uint16{%s}\n\n", t.Name, t.Len, list(raw, 2, false))
		case tablespec.SignedWords:
			fmt.Fprintf(&b, "var %s = [%d]int16{%s}\n\n", t.Name, t.Len, list(raw, 2, true))
		default: // strings: Len Pascal strings of Kind.Size() bytes each
			fmt.Fprintf(&b, "var %s = [%d]string{", t.Name, t.Len)
			for i := 0; i < t.Len; i++ {
				s := raw[i*t.Kind.Size():]
				fmt.Fprintf(&b, "%q, ", string(s[1:1+int(s[0])]))
			}
			b.WriteString("}\n\n")
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		os.Stdout.Write(b.Bytes())
		log.Fatal(err)
	}
	os.Stdout.Write(src)
}

func list(raw []byte, size int, signed bool) string {
	var parts []string
	for i := 0; i+size <= len(raw); i += size {
		v := int(raw[i])
		if size == 2 {
			v |= int(raw[i+1]) << 8
		}
		if signed && v >= 1<<(8*size-1) {
			v -= 1 << (8 * size)
		}
		parts = append(parts, fmt.Sprint(v))
	}
	return strings.Join(parts, ", ")
}
